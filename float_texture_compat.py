"""Reflect validated, packed float-2D SRVs for the native depth view bridge."""
import hashlib,json,re
from pathlib import Path
from static_derivative_compat import preserve_conditional_sampling

def emit_float_texture_compat(root):
    root=Path(root);rows=set();audits=[];packages={}
    for category,manifest_name,package_name in (
        ('ui','native-ui-binding-preparation.json','gpu-ui-graphics-package.inc'),
        ('static','native-static-graphics-binding-preparation.json','gpu-static-graphics-package.inc'),
        ('material','native-material-graphics-binding-preparation.json','gpu-material-graphics-package.inc')):
        manifest=root/'build/shaders'/manifest_name
        if not manifest.exists():continue
        package=(root/'src'/package_name).read_text()
        packages[package_name]=hashlib.sha256((root/'src'/package_name).read_bytes()).hexdigest()
        for shader in json.loads(manifest.read_text())['Shaders']:
            if not shader['RegisterMappingVerified'] or not shader['UniformRoundtripVerified']:continue
            native=Path(shader['Path']).read_bytes();wgsl=Path(shader['WGSL']).read_bytes()
            assert hashlib.sha256(native).hexdigest()==shader['SHA256']
            assert hashlib.sha256(wgsl).hexdigest()==shader['WGSLSHA256']
            text=preserve_conditional_sampling(shader,wgsl.decode(),root)
            # Same stencil .y->.x lowering the package generators apply after derivative compat.
            from stencil_component_lowering import lower_stencil_reads
            text,_=lower_stencil_reads(text,shader['Path'],576)
            digest=hashlib.sha256(text.encode()).hexdigest()
            stage='Vertex' if shader['Stage']=='vertex' else 'Pixel'
            assert shader['Stage'] in ('vertex','pixel')
            # Verify the runtime package has this precise original identity and
            # prepared WGSL version, including any audited derivative lowering.
            assert re.search(r'\{"'+re.escape(shader['Hash'])+r'",\s*GraphicsShaderStage::'+stage+r',\s*"'+digest+r'"',package)
            for resource in shader['Resources']:
                if resource['Kind']!='TextureSRV':continue
                group,binding=resource['Group'],resource['Binding']
                declaration=re.search(r'@group\('+str(group)+r'\)\s+@binding\('+str(binding)+r'\)\s+var\s+(\w+)\s*:\s*texture_2d<f32>\s*;',text)
                if not declaration:continue
                row=(shader['Hash'],stage,digest,binding,group)
                rows.add(row)
                audits.append(dict(Category=category,OriginalHash=shader['Hash'],Stage=shader['Stage'],
                    OriginalBytecodeSHA256=shader['SHA256'],RuntimeWGSL=digest,Group=group,
                    Binding=binding,OriginalSlot=resource['OriginalSlot'],Variable=declaration[1],
                    ExactDeclaration=declaration[0]))
    assert rows
    lines=['// Generated by float_texture_compat.py from validated packed shader interfaces.',
        '// Only the actual native D32F, single-layer/mip/sample 2D descriptor',
        '// activates the real-value copy; color, depth-comparison, integer,',
        '// array, multisample and storage resources never select this table.',
        'struct Float2DTextureInterface {const char* hash; GraphicsShaderStage stage; const char* wgsl; Uint32 binding,group;};',
        'static const Float2DTextureInterface kFloat2DTextureInterfaces[]={']
    for shader,stage,digest,binding,group in sorted(rows):
        lines.append('{'+json.dumps(shader)+',GraphicsShaderStage::'+stage+','+json.dumps(digest)+','+str(binding)+','+str(group)+'},')
    lines.append('};')
    output='\n'.join(lines)+'\n'
    generated=root/'src/gpu-float-texture-interfaces.inc'
    if not generated.exists() or generated.read_text()!=output:generated.write_text(output)
    proof=dict(Interfaces=len(rows),ShaderVersions=len({r[:3] for r in rows}),
        GeneratedSHA256=hashlib.sha256(generated.read_bytes()).hexdigest(),Packages=packages,Resources=audits,
        Scope='Exact packed WGSL float-2D declarations and original bytecode identities. Actual native D32F descriptor activates existing real-value copy. This is interface reflection, not full shader/game parity.')
    (root/'build/shaders/float-texture-interface-proof.json').write_text(json.dumps(proof,indent=2))
    return {k:proof[k] for k in ('Interfaces','ShaderVersions','GeneratedSHA256')}

if __name__=='__main__':print(json.dumps(emit_float_texture_compat(Path(__file__).resolve().parent),indent=2))
